#!/usr/bin/env python3
"""Compile marquee scroll text into MADS assembly data for Atari 8-bit.

Converts plain text (UTF-8, with optional Polish diacritics) into Atari
ANTIC 2 internal screen display codes, adding trailing padding spaces if needed
for smooth continuous loop scrolling.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

# Polish diacritics mapping for Atari 8-bit custom font
POLISH_CHARS: dict[str, int] = {
    # Uppercase
    "Ą": 65,
    "Ć": 66,
    "Ę": 67,
    "Ł": 68,
    "Ń": 69,
    "Ó": 70,
    "Ś": 71,
    "Ź": 72,
    "Ż": 73,
    # Lowercase
    "ą": 81,
    "ć": 82,
    "ę": 83,
    "ł": 84,
    "ń": 85,
    "ó": 86,
    "ś": 87,
    "ź": 88,
    "ż": 89,
}


def char_to_screencode(c: str) -> int:
    """Convert Unicode character to Atari ANTIC 2 internal screen code (0..127)."""
    if c in POLISH_CHARS:
        return POLISH_CHARS[c]
    val = ord(c)
    if 32 <= val <= 95:
        return val - 32
    if 96 <= val <= 127:
        return val
    if 0 <= val <= 31:
        return val + 64
    return 0  # Default to blank space


def compile_scroll_text(
    input_path: Path,
    output_path: Path,
    min_trailing_spaces: int = 24,
) -> int:
    """Read text from input_path, pad loop gap, and generate MADS assembly."""
    if not input_path.exists():
        print(f"Error: Scroll text file '{input_path}' not found.", file=sys.stderr)
        return 1

    raw_text = input_path.read_text(encoding="utf-8").rstrip("\r\n")
    if not raw_text:
        print(f"Error: Scroll text file '{input_path}' is empty.", file=sys.stderr)
        return 1

    # Ensure adequate trailing spaces between loop repetitions
    trailing_spaces = len(raw_text) - len(raw_text.rstrip(" "))
    if trailing_spaces < min_trailing_spaces:
        text = raw_text + (" " * (min_trailing_spaces - trailing_spaces))
    else:
        text = raw_text

    if len(text) > 255:
        print(
            f"Error: Scroll text length ({len(text)}) exceeds 255 bytes (8-bit index limit).",
            file=sys.stderr,
        )
        return 1

    encoded_bytes = [char_to_screencode(c) for c in text]

    lines: list[str] = [
        "; ==============================================================================",
        "; AUTO-GENERATED BY scripts/compile_scroll_text.py - DO NOT EDIT DIRECTLY",
        f"; Source: {input_path.as_posix()} ({len(text)} characters)",
        "; ==============================================================================",
        "",
        f"TITLE_SCROLL_TEXT_LEN = {len(text)}",
        "",
        "title_scroll_text",
    ]

    # Format bytes in chunks of 16 for readability
    chunk_size = 16
    for i in range(0, len(encoded_bytes), chunk_size):
        chunk = encoded_bytes[i : i + chunk_size]
        byte_strs = [f"${b:02X}" for b in chunk]
        lines.append(f"    .byte {', '.join(byte_strs)}")

    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"Generated scroll text: '{input_path}' -> '{output_path}' ({len(text)} chars)"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compile marquee scroll text into MADS assembly."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=Path("scroll/title.txt"),
        help="Input text file path (default: scroll/title.txt)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("gen/title_scroll_text.asm"),
        help="Output ASM file path (default: gen/title_scroll_text.asm)",
    )
    parser.add_argument(
        "--spaces",
        type=int,
        default=24,
        help="Minimum trailing spaces for loop gap (default: 24)",
    )
    args = parser.parse_args()
    return compile_scroll_text(args.input, args.output, min_trailing_spaces=args.spaces)


if __name__ == "__main__":
    sys.exit(main())
