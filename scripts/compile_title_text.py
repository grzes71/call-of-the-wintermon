#!/usr/bin/env python3
"""Compile title screen text from texts/title.txt into MADS assembly for Atari 8-bit.

Converts plain text lines into Atari ANTIC internal screen codes and computes
horizontal centering offsets for each line in 40-byte 2bpp mode.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

# Polish diacritics mapping for Atari 8-bit custom font
POLISH_CHARS: dict[str, int] = {
    # Uppercase
    "Ą": 65,
    "Ć": 66,
    "Ę": 67,
    "Ł": 68,
    "Ń": 69,
    "Ó": 70,
    "Ś": 71,
    "Ź": 72,
    "Ż": 73,
    # Lowercase
    "ą": 81,
    "ć": 82,
    "ę": 83,
    "ł": 84,
    "ń": 85,
    "ó": 86,
    "ś": 87,
    "ź": 88,
    "ż": 89,
}


def char_to_screencode(c: str) -> int:
    """Convert Unicode character to Atari ANTIC internal screen code (0..127)."""
    if c in POLISH_CHARS:
        return POLISH_CHARS[c]
    val = ord(c)
    if 32 <= val <= 95:
        return val - 32
    if 96 <= val <= 127:
        return val
    if 0 <= val <= 31:
        return val + 64
    return 0


def calculate_centering_offset(char_count: int, pitch: int = 40) -> int:
    """Calculate horizontal offset in bytes to center 2bpp text (2 bytes/char) on a row."""
    text_width_bytes = char_count * 2
    if text_width_bytes > pitch:
        raise ValueError(f"Text width ({text_width_bytes} bytes) exceeds row pitch ({pitch} bytes)")
    return (pitch - text_width_bytes) // 2


def compile_title_text(input_path: Path, output_path: Path) -> int:
    """Read lines from input_path, validate, center, and generate MADS assembly."""
    if not input_path.exists():
        print(f"Error: Title text file '{input_path}' not found.", file=sys.stderr)
        return 1

    raw_lines = [line.rstrip("\r\n") for line in input_path.read_text(encoding="utf-8").splitlines()]
    # Ignore empty lines at the very end if any
    while raw_lines and not raw_lines[-1].strip():
        raw_lines.pop()

    if len(raw_lines) != 3:
        print(
            f"Error: Expected exactly 3 title lines in '{input_path}', found {len(raw_lines)}.",
            file=sys.stderr,
        )
        return 1

    lines_data: list[dict[str, object]] = []
    for idx, line in enumerate(raw_lines, start=1):
        if not line:
            print(f"Error: Line {idx} in '{input_path}' is empty.", file=sys.stderr)
            return 1
        if len(line) > 20:
            print(
                f"Error: Line {idx} length ({len(line)}) exceeds max 20 characters: '{line}'",
                file=sys.stderr,
            )
            return 1

        offset = calculate_centering_offset(len(line), pitch=40)
        codes = [char_to_screencode(c) for c in line]
        lines_data.append(
            {
                "idx": idx,
                "text": line,
                "len": len(line),
                "offset": offset,
                "codes": codes,
            }
        )

    asm_lines: list[str] = [
        "; ==============================================================================",
        "; AUTO-GENERATED BY scripts/compile_title_text.py - DO NOT EDIT DIRECTLY",
        f"; Source: {input_path.as_posix()}",
        "; ==============================================================================",
        "",
    ]

    for item in lines_data:
        i = item["idx"]
        l_len = item["len"]
        l_off = item["offset"]
        txt = item["text"]
        asm_lines.extend(
            [
                f"; Line {i}: \"{txt}\" (length={l_len}, centered offset={l_off})",
                f"TITLE_LINE{i}_LEN       = {l_len}",
                f"TITLE_LINE{i}_OFFSET    = {l_off}",
            ]
        )

    asm_lines.extend(
        [
            "",
            "; Aliases for backward compatibility",
            "TITLE_CALL_LEN        = TITLE_LINE1_LEN",
            "TITLE_CALL_OFFSET     = TITLE_LINE1_OFFSET",
            "TITLE_OF_THE_LEN      = TITLE_LINE2_LEN",
            "TITLE_OF_THE_OFFSET   = TITLE_LINE2_OFFSET",
            "TITLE_WINTERMOON_LEN  = TITLE_LINE3_LEN",
            "TITLE_WINTERMOON_OFFSET = TITLE_LINE3_OFFSET",
            "",
            "; Compile-time bounds assertions",
        ]
    )

    for i in (1, 2, 3):
        asm_lines.extend(
            [
                f".if (TITLE_LINE{i}_LEN < 1) || (TITLE_LINE{i}_LEN > 20) || (TITLE_LINE{i}_OFFSET >= 40) || (TITLE_LINE{i}_OFFSET + TITLE_LINE{i}_LEN * 2 > 40)",
                f'    .error "Invalid TITLE_LINE{i} bounds"',
                ".endif",
            ]
        )

    asm_lines.extend(
        [
            "",
            "; Screen codes for title lines (not ASCII, no null terminator)",
        ]
    )

    aliases = [
        ("title_text_line1_codes", "title_text_call_codes"),
        ("title_text_line2_codes", "title_text_of_the_codes"),
        ("title_text_line3_codes", "title_text_wintermoon_codes"),
    ]

    for item, (label_primary, label_alias) in zip(lines_data, aliases):
        codes = item["codes"]
        hex_strs = [f"${c:02X}" for c in codes]
        asm_lines.extend(
            [
                f"{label_primary}:",
                f"{label_alias}:",
                f"    .byte {','.join(hex_strs)}",
                "",
            ]
        )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(asm_lines) + "\n", encoding="utf-8")
    print(
        f"Generated Title text: '{input_path}' -> '{output_path}' "
        f"(3 lines: {lines_data[0]['len']} chars/off {lines_data[0]['offset']}, "
        f"{lines_data[1]['len']} chars/off {lines_data[1]['offset']}, "
        f"{lines_data[2]['len']} chars/off {lines_data[2]['offset']})"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compile title screen text file into Atari 8-bit MADS assembly."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=Path("texts/title.txt"),
        help="Input UTF-8 text file containing 3 title lines (default: texts/title.txt)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("gen/title_text_data.asm"),
        help="Output MADS assembly file (default: gen/title_text_data.asm)",
    )
    args = parser.parse_args()
    return compile_title_text(args.input, args.output)


if __name__ == "__main__":
    sys.exit(main())
