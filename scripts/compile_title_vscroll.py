#!/usr/bin/env python3
"""Compile vertical scroll text lines from scroll/title.txt into MADS assembly data for Atari 8-bit.

Converts plain text (UTF-8, with optional Polish diacritics) into Atari
ANTIC 2 internal screen display codes, horizontally centered and padded with spaces to 40 bytes.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

# Polish diacritics mapping for Atari 8-bit custom font
POLISH_CHARS: dict[str, int] = {
    # Uppercase
    "Ą": 65,
    "Ć": 66,
    "Ę": 67,
    "Ł": 68,
    "Ń": 69,
    "Ó": 70,
    "Ś": 71,
    "Ź": 72,
    "Ż": 73,
    # Lowercase
    "ą": 81,
    "ć": 82,
    "ę": 83,
    "ł": 84,
    "ń": 85,
    "ó": 86,
    "ś": 87,
    "ź": 88,
    "ż": 89,
}


def char_to_screencode(c: str) -> int:
    """Convert Unicode character to Atari ANTIC 2 internal screen code (0..127)."""
    if c in POLISH_CHARS:
        return POLISH_CHARS[c]
    val = ord(c)
    if 32 <= val <= 95:
        return val - 32
    if 96 <= val <= 127:
        return val
    if 0 <= val <= 31:
        return val + 64
    return 0  # Default to blank space


def compile_title_vscroll(input_path: Path, output_path: Path) -> int:
    """Read lines from input_path, validate length, center text to 40B, and generate MADS assembly."""
    if not input_path.exists():
        print(f"Error: Scroll text file '{input_path}' not found.", file=sys.stderr)
        return 1

    content = input_path.read_text(encoding="utf-8")
    raw_lines = [line.rstrip("\r\n").rstrip() for line in content.splitlines()]
    lines = [line for line in raw_lines if line]  # Skip empty lines

    if not lines:
        print(f"Error: Scroll text file '{input_path}' contains no non-empty lines.", file=sys.stderr)
        return 1

    for line_num, line in enumerate(lines, 1):
        if len(line) > 40:
            msg = f"Line {line_num} in '{input_path}' exceeds 40-character limit (length {len(line)}): '{line}'"
            print(f"Error: {msg}", file=sys.stderr)
            raise ValueError(msg)

    count = len(lines)
    if count > 255:
        print(f"Error: Number of lines ({count}) exceeds 255.", file=sys.stderr)
        return 1

    out_lines: list[str] = [
        "; ==============================================================================",
        "; AUTO-GENERATED BY scripts/compile_title_vscroll.py - DO NOT EDIT DIRECTLY",
        f"; Source: {input_path.as_posix()} ({count} messages)",
        "; ==============================================================================",
        "",
        f"TITLE_VS_COUNT = {count}",
        "",
        ".if (TITLE_VS_COUNT < 1) || (TITLE_VS_COUNT > 255)",
        '    .error "TITLE_VS_COUNT must be between 1 and 255"',
        ".endif",
        "",
        "title_vs_lines:",
    ]

    for idx, line in enumerate(lines):
        spaces_left = (40 - len(line)) // 2
        spaces_right = 40 - len(line) - spaces_left
        padded_line = (" " * spaces_left) + line + (" " * spaces_right)
        encoded = [char_to_screencode(c) for c in padded_line]

        out_lines.append(f"; Message {idx}: \"{line}\" (len {len(line)}, offset {spaces_left})")
        for i in range(0, 40, 20):
            chunk = encoded[i : i + 20]
            byte_strs = [f"${b:02X}" for b in chunk]
            out_lines.append(f"    .byte {', '.join(byte_strs)}")

    out_lines.append("")
    out_lines.append("; Pointer tables for fast 40-byte line retrieval")
    out_lines.append("title_vs_lines_ptr_lo:")
    for idx in range(count):
        out_lines.append(f"    .byte <(title_vs_lines + {idx * 40})")
    out_lines.append("title_vs_lines_ptr_hi:")
    for idx in range(count):
        out_lines.append(f"    .byte >(title_vs_lines + {idx * 40})")
    out_lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(out_lines), encoding="utf-8")
    print(f"Generated vertical scroll data: '{input_path}' -> '{output_path}' ({count} lines)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compile title vertical scroll lines into MADS assembly."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=Path("scroll/title.txt"),
        help="Input text file path (default: scroll/title.txt)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("gen/title_vscroll_data.asm"),
        help="Output ASM file path (default: gen/title_vscroll_data.asm)",
    )
    args = parser.parse_args()
    try:
        return compile_title_vscroll(args.input, args.output)
    except ValueError:
        return 1


if __name__ == "__main__":
    sys.exit(main())
