#!/usr/bin/env python3
"""Compile the Game Over screen texts into compact MADS data (gen/gameover_texts.inc).

Input:  texts/failure.txt, texts/success.txt (UTF-8, one screen line per text line)
Output: MADS include with, per variant:

    gameover_<variant>_text:
        .byte N                    ; number of lines (0..GAMEOVER_MAX_LINES)
        .byte len, <len codes>     ; repeated N times (len = 0 for an empty line)

The 6502 code centres each line while copying (left margin = (40 - len) / 2), so the
data stays compact instead of storing 2 x 720 pre-padded bytes.

Character conversion uses the *same* mapping as the marquee scroll converter
(scripts/compile_scroll_text.py) - no second mapping is invented here. Unknown
characters are a build error (never silently blanked), and the only normalisation
applied is typographic punctuation -> its ASCII equivalent (e.g. an en/em dash to a
plain hyphen), which keeps the rendered glyph meaningful.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

try:  # run as a script (python scripts/convert_gameover_texts.py)
    from compile_scroll_text import POLISH_CHARS, char_to_screencode
except ImportError:  # pragma: no cover - imported as scripts.convert_gameover_texts
    from scripts.compile_scroll_text import POLISH_CHARS, char_to_screencode

GAMEOVER_MAX_LINES = 18
GAMEOVER_LINE_WIDTH = 40

# Typographic characters that the font cannot represent, mapped to their ASCII
# equivalent so the meaning survives (an em dash still renders as a dash).
TYPOGRAPHIC_NORMALISATION: dict[str, str] = {
    "\u2014": "-",   # em dash
    "\u2013": "-",   # en dash
    "\u2012": "-",   # figure dash
    "\u2018": "'",   # left single quote
    "\u2019": "'",   # right single quote
    "\u201c": '"',   # left double quote
    "\u201d": '"',   # right double quote
}


class GameOverTextError(Exception):
    """Raised for any invalid input file (missing, too many lines, bad character)."""


def normalise_char(c: str) -> str:
    """Map typographic punctuation to its ASCII equivalent (other chars pass through)."""
    return TYPOGRAPHIC_NORMALISATION.get(c, c)


def encode_line(text: str, source: str, line_no: int) -> list[int]:
    """Convert one text line to screen codes, raising on characters the font lacks."""
    codes: list[int] = []
    for column, raw in enumerate(text, start=1):
        c = normalise_char(raw)
        if c != " " and c not in POLISH_CHARS:
            val = ord(c)
            if not (32 <= val <= 127):
                raise GameOverTextError(
                    f"{source}: line {line_no}, column {column}: character {raw!r} "
                    f"(U+{ord(raw):04X}) has no glyph in the font"
                )
        codes.append(char_to_screencode(c))
    return codes


def parse_text_file(path: Path) -> list[list[int]]:
    """Read a Game Over text file into a list of encoded lines (empty lines kept)."""
    if not path.is_file():
        raise GameOverTextError(f"Missing text file: {path}")

    content = path.read_text(encoding="utf-8")

    # Split on \n / \r\n; a single trailing newline must not create an extra empty line,
    # while every other line - including empty ones - is kept in order.
    if content.endswith("\r\n"):
        content = content[:-2]
    elif content.endswith("\n"):
        content = content[:-1]
    lines = content.split("\n") if content else []

    if len(lines) > GAMEOVER_MAX_LINES:
        raise GameOverTextError(
            f"{path}: {len(lines)} lines exceed the {GAMEOVER_MAX_LINES}-line screen area"
        )

    encoded: list[list[int]] = []
    for index, raw_line in enumerate(lines, start=1):
        line = raw_line.rstrip("\r").rstrip()      # trailing spaces only
        if len(line) > GAMEOVER_LINE_WIDTH:
            raise GameOverTextError(
                f"{path}: line {index} is {len(line)} characters long "
                f"(maximum {GAMEOVER_LINE_WIDTH}): {line!r}"
            )
        encoded.append(encode_line(line, str(path), index))
    return encoded



def render_include(variants: dict[str, list[list[int]]], sources: dict[str, str]) -> str:
    """Render the MADS include for all variants."""
    out: list[str] = [
        "; ==============================================================================",
        "; AUTO-GENERATED BY scripts/convert_gameover_texts.py - DO NOT EDIT DIRECTLY",
    ]
    for name, source in sources.items():
        out.append(f";   {name}: {source} ({len(variants[name])} lines)")
    out.extend([
        "; ==============================================================================",
        "",
        f"GAMEOVER_MAX_LINES = {GAMEOVER_MAX_LINES}",
        "",
    ])

    for name, lines in variants.items():
        out.append(f"; --- {name.upper()} ({len(lines)} lines) ---")
        out.append(f"gameover_{name}_text:")
        out.append(f"    .byte {len(lines)}")
        for line in lines:
            if line:
                codes = ", ".join(f"${code:02X}" for code in line)
                out.append(f"    .byte {len(line)}, {codes}")
            else:
                out.append("    .byte 0")
        out.append("")

    return "\n".join(out)


def compile_gameover_texts(
    output_path: Path,
    failure_path: Path = Path("texts/failure.txt"),
    success_path: Path = Path("texts/success.txt"),
) -> int:
    """Compile both Game Over texts; returns 0 on success, 1 on any validation error."""
    sources = {"failure": str(failure_path), "success": str(success_path)}
    try:
        variants = {
            "failure": parse_text_file(failure_path),
            "success": parse_text_file(success_path),
        }
    except GameOverTextError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_include(variants, sources), encoding="utf-8")
    print(
        "Generated Game Over texts: "
        + ", ".join(f"{name}={len(lines)} lines" for name, lines in variants.items())
        + f" -> {output_path}"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compile Game Over screen texts into a MADS include."
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("gen/gameover_texts.inc"),
        help="Output include path (default: gen/gameover_texts.inc)",
    )
    parser.add_argument(
        "--failure",
        type=Path,
        default=Path("texts/failure.txt"),
        help="Failure text file (default: texts/failure.txt)",
    )
    parser.add_argument(
        "--success",
        type=Path,
        default=Path("texts/success.txt"),
        help="Success text file (default: texts/success.txt)",
    )
    args = parser.parse_args()
    return compile_gameover_texts(args.output, args.failure, args.success)


if __name__ == "__main__":
    sys.exit(main())
